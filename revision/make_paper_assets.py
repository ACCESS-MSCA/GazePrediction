def msd(v, nd=2):
    v = np.asarray(v, float)
    return f"{v.mean():.{nd}f} $\\pm$ {v.std(ddof=1):.{nd}f}" if len(v) > 1 else f"{v.mean():.{nd}f}"


def tex_minus(t):
    """Typeset a hyphen before a number (e.g. -0.46) as a math minus."""
    return re.sub(r"(^|[\s(\[,:])-(\d)", r"\1$-$\2", t)


def write_tex(name, caption, label, colspec, header, rows, notes=None):
    rows = [r if r == "MID" else tex_minus(r) for r in rows]
    notes = tex_minus(notes) if notes else notes
    lines = ["% Auto-generated by eht_gaze_prediction/revision/make_paper_assets.py - do not edit by hand",
             "\\begin{table}[t]", "\\centering", "\\footnotesize", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
             f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", header + " \\\\", "\\midrule"]
    for r in rows:
        lines.append("\\midrule" if r == "MID" else (r if r.startswith("\\") else r + " \\\\"))
    lines += ["\\bottomrule", "\\end{tabular}"]
    if notes:
        lines += ["\\par\\smallskip", f"\\parbox{{\\linewidth}}{{\\scriptsize {notes}}}"]
    lines.append("\\end{table}")
    with open(os.path.join(TAB, name + ".tex"), "w") as f:
        f.write("\n".join(lines) + "\n")


def save(fig, name):
    fig.savefig(os.path.join(FIG, name + ".pdf"))
    fig.savefig(os.path.join(FIG, name + ".png"), dpi=300)
    plt.close(fig)


