def policy_eval(z_te, z_va, tau=10, sp_te=None, sp_va=None):
    hz = select_horizons(z_va["err"], z_va["pred_task"], tau)
    h = np.array([hz[c] for c in z_te["pred_task"]])
    n = np.arange(len(h))
    res = {"hz": hz, "h": h, "adaptive": z_te["err"][n, h - 1], "hmd": z_te["hmd_err"][n, h - 1]}
    m = h.mean()
    lo = int(m)
    hm = np.where(RNG.random(len(h)) < m - lo, lo + 1, lo)
    res["fixed"] = z_te["err"][n, hm - 1]
    res["random"] = z_te["err"][n, RNG.permutation(h) - 1]
    hz_gt = select_horizons(z_va["err"], z_va["task"], tau) if z_va["task"].max() > 0 else None
    if hz_gt is not None and z_te["task"].max() > 0:
        h_or = np.array([hz_gt[c] for c in z_te["task"]])
        res["oracle"], res["oracle_h"], res["oracle_hz"] = z_te["err"][n, h_or - 1], h_or, hz_gt
    if sp_te is not None:
        q = np.quantile(sp_va, [0.25, 0.5, 0.75])
        hs = select_horizons(z_va["err"], np.digitize(sp_va, q), tau)
        h2 = np.array([hs[c] for c in np.digitize(sp_te, q)])
        m2 = h2.mean()
        lo2 = int(m2)
        hm2 = np.where(RNG.random(len(h2)) < m2 - lo2, lo2 + 1, lo2)
        res["speed"], res["speed_fixed"], res["speed_h"] = z_te["err"][n, h2 - 1], z_te["err"][n, hm2 - 1], h2
    return res


