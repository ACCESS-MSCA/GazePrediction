def ent_stats(z):
    p = np.clip(z["probs"], 1e-12, 1)
    H = -(p * np.log(p)).sum(1)
    pt = z["probs"].argmax(1)
    e = z["err"][:, 19]
    r = {"global": spearmanr(H, e)[0], "partial": partial_spearman(H, e, pt)}
    for i in range(4):
        m = pt == i
        r[i] = spearmanr(H[m], e[m])[0] if m.sum() > 20 else np.nan
    return r, H, pt, e


